# playground_db.py
# 문헌(Literature) Playground CRUD — Claude 기반 연구공간.
# 스키마: supabase_schema.sql 의 playgrounds / playground_messages / playground_papers.
# DB 접근 단일 진입점: db_config.get_engine() (database.py 와 동일 패턴).
from __future__ import annotations

from sqlalchemy import text, bindparam

from db_config import get_engine


# ── 스키마 보장(멱등) — 배포 DB 에 새 테이블이 없을 때 대비 ──
_PLAYGROUND_DDL = """
CREATE TABLE IF NOT EXISTS playgrounds (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT REFERENCES playgrounds(id) ON DELETE CASCADE,
    uniprot_id  TEXT,
    name        TEXT NOT NULL,
    digest      TEXT,
    digest_updated_at TIMESTAMPTZ,
    created_at  TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_playgrounds_uniprot ON playgrounds(uniprot_id);
CREATE INDEX IF NOT EXISTS idx_playgrounds_parent  ON playgrounds(parent_id);
CREATE TABLE IF NOT EXISTS playground_messages (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playground_id BIGINT NOT NULL REFERENCES playgrounds(id) ON DELETE CASCADE,
    role          TEXT NOT NULL,
    content       TEXT,
    created_at    TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_playground_messages_pg ON playground_messages(playground_id);
CREATE TABLE IF NOT EXISTS playground_papers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playground_id BIGINT NOT NULL REFERENCES playgrounds(id) ON DELETE CASCADE,
    title         TEXT,
    doi           TEXT,
    storage_path  TEXT,
    matched_structure_id TEXT,
    matched       BOOLEAN DEFAULT FALSE,
    created_at    TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_playground_papers_pg ON playground_papers(playground_id);
"""

_ensured = False


def ensure_playground_schema() -> None:
    """새 Playground 테이블이 없으면 생성(멱등). 최초 1회만 실행."""
    global _ensured
    if _ensured:
        return
    try:
        with get_engine().begin() as conn:
            conn.exec_driver_sql(_PLAYGROUND_DDL)
        _ensured = True
    except Exception as e:
        print(f"[WARN] Playground 스키마 보장 실패: {e}")


