def create_playground(uniprot_id: str, name: str, parent_id=None) -> int:
    """Playground 생성 → 새 id 반환. parent_id 지정 시 중첩(하위)."""
    ensure_playground_schema()
    with get_engine().begin() as conn:
        row = conn.execute(text("""
            INSERT INTO playgrounds (uniprot_id, name, parent_id)
            VALUES (:uid, :name, :pid)
            RETURNING id
        """), {"uid": uniprot_id or None, "name": (name or "새 주제").strip(),
               "pid": parent_id}).first()
    return int(row[0]) if row else 0


def list_playgrounds(uniprot_id: str) -> list[dict]:
    """이 단백질의 모든 Playground (트리 구성용 — parent_id 포함), 생성순."""
    ensure_playground_schema()
    with get_engine().connect() as conn:
        rows = conn.execute(text("""
            SELECT pg.id, pg.parent_id, pg.uniprot_id, pg.name,
                   (pg.digest IS NOT NULL AND pg.digest <> '') AS has_digest,
                   pg.digest_updated_at, pg.created_at,
                   (SELECT count(*) FROM playground_messages m
                      WHERE m.playground_id = pg.id) AS n_messages
            FROM playgrounds pg
            WHERE pg.uniprot_id = :uid OR (:uid IS NULL AND pg.uniprot_id IS NULL)
            ORDER BY pg.created_at ASC, pg.id ASC
        """), {"uid": uniprot_id or None}).mappings().all()
    out = []
    for r in rows:
        d = dict(r)
        d["id"] = int(d["id"])
        d["parent_id"] = int(d["parent_id"]) if d["parent_id"] is not None else 0
        d["name"] = d["name"] or "(이름 없음)"
        d["has_digest"] = bool(d["has_digest"])
        d["n_messages"] = int(d["n_messages"] or 0)
        d["created_at"] = str(d["created_at"]) if d["created_at"] else ""
        d["digest_updated_at"] = str(d["digest_updated_at"]) if d["digest_updated_at"] else ""
        out.append(d)
    return out


def get_playground(pid: int) -> dict | None:
    with get_engine().connect() as conn:
        row = conn.execute(text("""
            SELECT id, parent_id, uniprot_id, name, digest, digest_updated_at, created_at
            FROM playgrounds WHERE id = :id
        """), {"id": pid}).mappings().first()
    if not row:
        return None
    d = dict(row)
    d["id"] = int(d["id"])
    d["parent_id"] = int(d["parent_id"]) if d["parent_id"] is not None else 0
    d["name"] = d["name"] or "(이름 없음)"
    d["digest"] = d["digest"] or ""
    d["digest_updated_at"] = str(d["digest_updated_at"]) if d["digest_updated_at"] else ""
    return d


def rename_playground(pid: int, name: str) -> None:
    with get_engine().begin() as conn:
        conn.execute(text("UPDATE playgrounds SET name = :name WHERE id = :id"),
                     {"name": (name or "").strip() or "새 주제", "id": pid})


def update_digest(pid: int, digest: str) -> None:
    with get_engine().begin() as conn:
        conn.execute(text("""
            UPDATE playgrounds SET digest = :d, digest_updated_at = now() WHERE id = :id
        """), {"d": digest or "", "id": pid})


def delete_playground(pid: int) -> None:
    """Playground 삭제 (자식·메시지·문헌 cascade). Storage 객체도 정리."""
    # 하위 트리(자기 포함)의 storage_path 수집 → Storage 제거
    with get_engine().connect() as conn:
        ids = _descendant_ids(conn, pid)
        paths = []
        if ids:
            q = text("SELECT storage_path FROM playground_papers "
                     "WHERE playground_id IN :ids AND storage_path IS NOT NULL"
                     ).bindparams(bindparam("ids", expanding=True))
            paths = [r[0] for r in conn.execute(q, {"ids": ids}).all() if r[0]]
    if paths:
        try:
            from supabase_storage import _client, BUCKET
            _client().storage.from_(BUCKET).remove(paths)
        except Exception:
            pass
    with get_engine().begin() as conn:
        conn.execute(text("DELETE FROM playgrounds WHERE id = :id"), {"id": pid})


def _descendant_ids(conn, pid: int) -> list[int]:
    """pid 및 그 모든 하위 Playground id (재귀 CTE)."""
    rows = conn.execute(text("""
        WITH RECURSIVE tree AS (
            SELECT id FROM playgrounds WHERE id = :id
            UNION ALL
            SELECT pg.id FROM playgrounds pg JOIN tree t ON pg.parent_id = t.id
        )
        SELECT id FROM tree
    """), {"id": pid}).all()
    return [int(r[0]) for r in rows]


