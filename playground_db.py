# 문헌 ↔ DB papers 매칭 (DOI 우선, 제목 폴백)
# ═══════════════════════════════════════════
def _norm_title(t: str) -> str:
    import re
    return re.sub(r"[^a-z0-9]", "", (t or "").lower())


def match_paper_to_db(uniprot_id: str, title: str = "", doi: str = "") -> dict | None:
    """업로드/참조 문헌을 이 단백질의 DB 논문과 대조.

    DOI 정확일치 우선, 없으면 제목 정규화 후 부분일치. 매칭 시:
    {structure_id, title, doi, has_structured} 반환, 없으면 None.
    """
    doi = (doi or "").strip().lower()
    with get_engine().connect() as conn:
        if doi:
            row = conn.execute(text("""
                SELECT ps.structure_id, p.title, ps.doi,
                       (pa.structured IS NOT NULL) AS has_structured
                FROM pdb_structures ps
                LEFT JOIN papers p ON p.structure_id = ps.structure_id
                LEFT JOIN paper_analysis pa ON pa.structure_id = ps.structure_id
                WHERE ps.uniprot_id = :uid AND lower(ps.doi) = :doi
                LIMIT 1
            """), {"uid": uniprot_id, "doi": doi}).mappings().first()
            if row:
                return {"structure_id": row["structure_id"], "title": row["title"] or "",
                        "doi": row["doi"] or "", "has_structured": bool(row["has_structured"])}
        # 제목 폴백
        nt = _norm_title(title)
        if len(nt) >= 12:
            rows = conn.execute(text("""
                SELECT p.structure_id, p.title, ps.doi,
                       (pa.structured IS NOT NULL) AS has_structured
                FROM papers p
                JOIN pdb_structures ps ON p.structure_id = ps.structure_id
                LEFT JOIN paper_analysis pa ON pa.structure_id = p.structure_id
                WHERE ps.uniprot_id = :uid AND p.title IS NOT NULL
            """), {"uid": uniprot_id}).mappings().all()
            for r in rows:
                cand = _norm_title(r["title"])
                if cand and (cand in nt or nt in cand):
                    return {"structure_id": r["structure_id"], "title": r["title"] or "",
                            "doi": r["doi"] or "", "has_structured": bool(r["has_structured"])}
    return None
